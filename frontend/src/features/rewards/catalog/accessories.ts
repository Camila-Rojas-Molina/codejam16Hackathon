const BY_ID = new Map(ACCESSORIES.map((a) => [a.id, a]))

/** An accessory by id (retired ones included, so owned items still draw). */
export const accessoryById = (id: string | null | undefined): AccessoryDef | undefined => (id ? BY_ID.get(id) : undefined)

/** Where an accessory sits on an avatar, or undefined when it doesn't fit that avatar. */
export const accessoryFit = (item: AccessoryDef, avatarId: string): Fit | undefined => item.fits[avatarId]

/** Whether an accessory can be worn by an avatar. */
export const fitsAvatar = (item: AccessoryDef, avatarId: string): boolean => avatarId in item.fits
