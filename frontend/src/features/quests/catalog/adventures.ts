// TRAVEL ADVENTURES: three personalised suggestions per person per week, worth 125–300 points.
// Chosen by engine.ts (and the same rules in SQL) from interests, mode, accessibility needs and
// pace. The description is the idea; the objective is exactly what's checked (photos with a
// city, GPS-checked hunts, pinned cities). `{city}` = trip destination (tourist) or home city (local).
//
// company: 'solo' / 'either' never need anyone else. 'companion' adventures need a teammate and are
// only ever offered next to ones you can do alone.
// avoidFor: accessibility need ids (features/profile/options.ts) the adventure doesn't suit.
// Pure data: no React imports (scripts/gen-economy turns this into SQL). Never rename an id.
import type { QuestDef } from '../../economy/types'

const hunts = { label: 'Find a hunt', to: '/match' }
const gallery = { label: 'Open the gallery', to: '/gallery' }
const cityPhotos = (count: number) => ({ type: 'photos' as const, count, requireCity: true })

type Adv = Omit<QuestDef, 'category' | 'action' | 'objective'> & Partial<Pick<QuestDef, 'action' | 'objective'>>

const photoObjective = (n: number) => `Upload ${n} photo${n === 1 ? '' : 's'} tagged with ${n === 1 ? 'its' : 'their'} city`

function adv(a: Adv): QuestDef {
  const c = a.condition
  let objective = a.objective
  if (!objective && c.type === 'photos') objective = photoObjective(c.count)
  return {
    ...a,
    category: 'adventure',
    objective: objective ?? '',
    action: a.action ?? (c.type === 'hunts' ? hunts : gallery),
  }
}

